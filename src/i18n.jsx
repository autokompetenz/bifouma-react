const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('bifouma-lang') : null;
    return saved && translations[saved] ? saved : DEFAULT_LANG;
  });

  useEffect(() => {
    localStorage.setItem('bifouma-lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => {
    const keys = key.split('.');
    let o = translations[lang];
    for (const k of keys) o = o && o[k];
    if (o !== undefined) return o;
    o = translations[DEFAULT_LANG];
    for (const k of keys) o = o && o[k];
    return o !== undefined ? o : key;
  };

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);